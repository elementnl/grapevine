-- Why: daily games need a traversable drawing/guess tree with indexed depth.

begin;

create table if not exists public.players (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.days (
  date date primary key,
  initial_prompt text not null check (length(btrim(initial_prompt)) > 0),
  status text not null default 'scheduled'
    check (status in ('scheduled', 'live', 'frozen')),
  metadata jsonb not null default '{}'::jsonb
    check (jsonb_typeof(metadata) = 'object'),
  opened_at timestamptz,
  frozen_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.drawings (
  id bigint generated by default as identity primary key,
  day date not null references public.days (date) on delete cascade,
  parent_guess_id bigint,
  player_id uuid references public.players (id) on delete set null,
  strokes jsonb not null check (
    case
      when jsonb_typeof(strokes) = 'object'
        and strokes ->> 'v' = '1'
        and jsonb_typeof(strokes -> 'strokes') = 'array'
      then jsonb_array_length(strokes -> 'strokes') > 0
      else false
    end
  ),
  depth integer not null default 1 check (depth > 0 and depth % 2 = 1),
  status text not null default 'pending'
    check (status in ('pending', 'visible', 'rejected', 'pruned')),
  created_at timestamptz not null default now()
);

create table if not exists public.guesses (
  id bigint generated by default as identity primary key,
  day date not null references public.days (date) on delete cascade,
  drawing_id bigint not null,
  player_id uuid references public.players (id) on delete set null,
  text text not null check (length(btrim(text)) between 3 and 80),
  depth integer not null default 2 check (depth >= 2 and depth % 2 = 0),
  created_at timestamptz not null default now()
);

create unique index if not exists drawings_day_id_key
  on public.drawings (day, id);
create unique index if not exists guesses_day_id_key
  on public.guesses (day, id);

alter table public.guesses
  drop constraint if exists guesses_drawing_same_day_fkey;
alter table public.guesses
  add constraint guesses_drawing_same_day_fkey
  foreign key (day, drawing_id)
  references public.drawings (day, id)
  on delete cascade;

alter table public.drawings
  drop constraint if exists drawings_parent_guess_same_day_fkey;
alter table public.drawings
  add constraint drawings_parent_guess_same_day_fkey
  foreign key (day, parent_guess_id)
  references public.guesses (day, id)
  on delete cascade;

create index if not exists drawings_day_status_depth_idx
  on public.drawings (day, status, depth);
create index if not exists drawings_day_parent_guess_idx
  on public.drawings (day, parent_guess_id);
create index if not exists drawings_player_id_idx
  on public.drawings (player_id);
create index if not exists guesses_day_drawing_idx
  on public.guesses (day, drawing_id);
create index if not exists guesses_day_depth_idx
  on public.guesses (day, depth);
create index if not exists guesses_player_id_idx
  on public.guesses (player_id);

create or replace function public.set_drawing_depth()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  parent_depth integer;
begin
  if tg_op = 'UPDATE' and (
    new.day is distinct from old.day
    or new.parent_guess_id is distinct from old.parent_guess_id
  ) then
    raise exception 'a drawing cannot be moved to another day or parent'
      using errcode = 'check_violation';
  end if;

  if new.parent_guess_id is null then
    new.depth := 1;
  else
    select guesses.depth
      into parent_depth
      from public.guesses
      where guesses.day = new.day
        and guesses.id = new.parent_guess_id;

    if not found then
      raise exception 'the parent guess must exist on the same day'
        using errcode = 'foreign_key_violation';
    end if;

    new.depth := parent_depth + 1;
  end if;

  return new;
end;
$$;

create or replace function public.set_guess_depth()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  parent_depth integer;
begin
  if tg_op = 'UPDATE' and (
    new.day is distinct from old.day
    or new.drawing_id is distinct from old.drawing_id
  ) then
    raise exception 'a guess cannot be moved to another day or drawing'
      using errcode = 'check_violation';
  end if;

  select drawings.depth
    into parent_depth
    from public.drawings
    where drawings.day = new.day
      and drawings.id = new.drawing_id;

  if not found then
    raise exception 'the parent drawing must exist on the same day'
      using errcode = 'foreign_key_violation';
  end if;

  new.depth := parent_depth + 1;
  return new;
end;
$$;

drop trigger if exists drawings_set_depth on public.drawings;
create trigger drawings_set_depth
  before insert or update on public.drawings
  for each row execute function public.set_drawing_depth();

drop trigger if exists guesses_set_depth on public.guesses;
create trigger guesses_set_depth
  before insert or update on public.guesses
  for each row execute function public.set_guess_depth();

alter table public.players enable row level security;
alter table public.days enable row level security;
alter table public.drawings enable row level security;
alter table public.guesses enable row level security;

commit;
